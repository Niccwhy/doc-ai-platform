CREATE TABLE email_inbox (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id          BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE CASCADE,
    config_id        BIGINT      NOT NULL,                      -- 来源邮箱配置 ID
    message_uid      BIGINT      NOT NULL,                      -- 邮件在 IMAP 中的 UID
    uid_validity     BIGINT      NOT NULL DEFAULT 0,            -- 入队时的 UIDVALIDITY，与 UID 共同构成幂等键
    attachment_index SMALLINT    NOT NULL DEFAULT 0,            -- 同一封邮件内的附件序号，从 0 开始
    from_addr        VARCHAR(255) NOT NULL,                     -- 发件人地址
    subject          VARCHAR(512),                              -- 邮件主题
    received_at      TIMESTAMPTZ,                               -- 邮件接收时间
    attachment_name  VARCHAR(255) NOT NULL,                     -- 附件文件名
    file_size        BIGINT      NOT NULL,
    sha256           CHAR(64)    NOT NULL,
    storage_key      VARCHAR(512) NOT NULL,
    status           VARCHAR(16) NOT NULL DEFAULT 'PENDING',    -- 状态：PENDING 待确认 / CLAIMED 已入库 / REJECTED 已驳回
    document_id      BIGINT,                                    -- 认领后生成的文件 ID
    reject_reason    VARCHAR(255),                              -- 驳回原因
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_inbox_status          CHECK (status IN ('PENDING', 'CLAIMED', 'REJECTED')),
    CONSTRAINT ck_inbox_claimed_doc     CHECK (status <> 'CLAIMED' OR document_id IS NOT NULL),
    CONSTRAINT ck_inbox_rejected_reason CHECK (status <> 'REJECTED' OR reject_reason IS NOT NULL),
    CONSTRAINT fk_inbox_config FOREIGN KEY (config_id, dept_id)
        REFERENCES dept_email_config (id, dept_id) ON DELETE CASCADE,
    CONSTRAINT fk_inbox_doc FOREIGN KEY (document_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE RESTRICT
);

