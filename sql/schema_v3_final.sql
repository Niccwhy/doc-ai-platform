CREATE UNIQUE INDEX uq_dept_parent_name ON sys_dept (parent_id, name)
    NULLS NOT DISTINCT WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_dept_code ON sys_dept (dept_code)
    WHERE deleted_at IS NULL AND dept_code IS NOT NULL;

CREATE UNIQUE INDEX uq_user_username ON sys_user (username) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_user_email ON sys_user (dept_id, lower(email))
    WHERE deleted_at IS NULL AND email IS NOT NULL;
CREATE INDEX idx_user_dept_role ON sys_user (dept_id, role) WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX uq_email_cfg_addr ON dept_email_config (dept_id, lower(email_address))
    WHERE deleted_at IS NULL;
CREATE INDEX idx_email_cfg_enabled ON dept_email_config (enabled) WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX uq_wl_pattern ON email_whitelist (dept_id, match_type, lower(pattern));

CREATE UNIQUE INDEX uq_tag_name ON sys_tag (dept_id, lower(tag_name)) WHERE deleted_at IS NULL;

CREATE INDEX idx_doc_dept_cat_time ON document (dept_id, file_category, created_at DESC)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_doc_parse_pending ON document (parse_status)
    WHERE deleted_at IS NULL AND parse_status IN ('UPLOADED', 'FAILED');
CREATE INDEX idx_doc_sha ON document (dept_id, sha256) WHERE deleted_at IS NULL;
CREATE INDEX idx_doc_shared ON document (is_shared) WHERE is_shared AND deleted_at IS NULL;

CREATE INDEX idx_dtr_tag_doc ON document_tag_rel (tag_id, document_id);
CREATE INDEX idx_dtr_dept ON document_tag_rel (dept_id, tag_id, document_id);

CREATE UNIQUE INDEX uq_ver_doc_no ON document_version (document_id, version_no);
CREATE INDEX idx_ver_dept_time ON document_version (dept_id, created_at DESC);

CREATE UNIQUE INDEX uq_inbox_uid ON email_inbox (config_id, uid_validity, message_uid, attachment_index);
CREATE INDEX idx_inbox_pending ON email_inbox (dept_id, status, created_at DESC)
    WHERE status = 'PENDING';

CREATE UNIQUE INDEX uq_block_doc_idx ON document_block (document_id, block_index);
CREATE INDEX idx_block_dept_doc ON document_block (dept_id, document_id, block_index);
CREATE INDEX idx_block_embedding ON document_block
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);
CREATE INDEX idx_block_content_trgm ON document_block USING gin (content gin_trgm_ops);

CREATE UNIQUE INDEX uq_schema_name_ver ON extract_schema (dept_id, name, version)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_schema_dept ON extract_schema (dept_id, status) WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX uq_tfm_field ON template_field_mapping (template_doc_id, field_key);
CREATE UNIQUE INDEX uq_tfm_anchor ON template_field_mapping
    (template_doc_id, anchor_type, COALESCE(sheet_name, ''), anchor_ref);

CREATE INDEX idx_task_dept_status ON task (dept_id, status, created_at DESC)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_task_dept_assignee ON task (dept_id, assignee_id, status)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_task_pending ON task (dept_id, priority, created_at)
    WHERE status = 'PENDING' AND deleted_at IS NULL;
CREATE INDEX idx_task_lease ON task (lease_expires_at)
    WHERE status = 'PROCESSING' AND lease_expires_at IS NOT NULL;

CREATE INDEX idx_tdr_doc ON task_document_rel (document_id, task_id);

CREATE UNIQUE INDEX uq_res_candidate ON extract_result (task_id, document_id, field_key);
CREATE UNIQUE INDEX uq_res_selected ON extract_result (task_id, field_key) WHERE is_selected;
CREATE INDEX idx_res_task ON extract_result (task_id, field_key);
CREATE INDEX idx_res_low_conf ON extract_result (dept_id, confidence) WHERE NOT is_verified;

CREATE INDEX idx_res_hist ON extract_result_history (result_id, created_at);
CREATE INDEX idx_res_hist_task ON extract_result_history (task_id, created_at);

CREATE INDEX idx_task_log_task ON task_log (task_id, created_at DESC);
CREATE INDEX idx_task_log_dept ON task_log (dept_id, created_at DESC);

CREATE INDEX idx_audit_dept_time ON sys_audit_log (dept_id, created_at DESC);
CREATE INDEX idx_audit_user_time ON sys_audit_log (user_id, created_at DESC);
CREATE INDEX idx_audit_action ON sys_audit_log (action, created_at DESC);
