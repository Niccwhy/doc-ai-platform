CREATE TABLE sys_tag (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id     BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE CASCADE,
    tag_name    VARCHAR(64) NOT NULL,                 -- 标签名，同部门内唯一（忽略大小写）
    color       VARCHAR(16),                          -- 标签颜色，前端色值
    sort_no     INT         NOT NULL DEFAULT 0,       -- 排序号
    created_by  BIGINT,                               -- 创建人
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ,
    CONSTRAINT uq_tag_id_dept UNIQUE (id, dept_id),
    CONSTRAINT fk_tag_creator FOREIGN KEY (created_by, dept_id)
        REFERENCES sys_user (id, dept_id) ON DELETE SET NULL (created_by)
);

CREATE TABLE document (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id        BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE RESTRICT,
    uploader_id    BIGINT,                                      -- 上传人；系统生成或邮件入库时为空
    uploader_type  VARCHAR(16) NOT NULL DEFAULT 'USER',         -- 上传来源：USER 用户 / SYSTEM 系统 / EMAIL 邮件
    file_name      VARCHAR(255) NOT NULL,                       -- 原始文件名
    file_type      VARCHAR(32) NOT NULL,                        -- 扩展名（小写）：docx/xlsx/md/txt/pdf
    mime_type      VARCHAR(128),                                -- MIME 类型
    file_category  VARCHAR(16) NOT NULL,                        -- 类别：SOURCE 源文件 / TEMPLATE 模板 / OUTPUT 产出
    file_size      BIGINT      NOT NULL,                        -- 文件字节数
    sha256         CHAR(64)    NOT NULL,                        -- 内容摘要，用于查重与内容寻址
    storage_bucket VARCHAR(64) NOT NULL DEFAULT 'docai',        -- 对象存储桶
    storage_key    VARCHAR(512) NOT NULL,                       -- 对象存储键
    source_type    VARCHAR(16) NOT NULL DEFAULT 'WEB',          -- 来源渠道：WEB 上传 / EMAIL 邮件 / API 接口
    source_ref     VARCHAR(255),                                -- 外部溯源标识，如邮件 Message-ID
    is_shared      BOOLEAN     NOT NULL DEFAULT FALSE,          -- 是否全部门可见的共有资产（如规范手册）
    parse_status   VARCHAR(16) NOT NULL DEFAULT 'UPLOADED',     -- 解析状态：UPLOADED/PARSING/PARSED/FAILED/SKIPPED
    parse_error    TEXT,                                        -- 解析失败原因
    parse_attempts SMALLINT    NOT NULL DEFAULT 0,              -- 已尝试解析次数
    parsed_at      TIMESTAMPTZ,                                 -- 解析完成时间
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ,
    CONSTRAINT ck_doc_category          CHECK (file_category IN ('SOURCE', 'TEMPLATE', 'OUTPUT')),
    CONSTRAINT ck_doc_status            CHECK (parse_status IN ('UPLOADED', 'PARSING', 'PARSED', 'FAILED', 'SKIPPED')),
    CONSTRAINT ck_doc_source            CHECK (source_type IN ('WEB', 'EMAIL', 'API')),
    CONSTRAINT ck_doc_size              CHECK (file_size >= 0),
    CONSTRAINT ck_doc_sha               CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_doc_parsed_at         CHECK (parse_status <> 'PARSED' OR parsed_at IS NOT NULL),
    CONSTRAINT ck_doc_failed_err        CHECK (parse_status <> 'FAILED' OR parse_error IS NOT NULL),
    CONSTRAINT ck_doc_uploader_required CHECK (uploader_type <> 'USER' OR uploader_id IS NOT NULL),
    CONSTRAINT uq_document_id_dept      UNIQUE (id, dept_id),
    CONSTRAINT fk_doc_uploader FOREIGN KEY (uploader_id, dept_id)
        REFERENCES sys_user (id, dept_id) ON DELETE RESTRICT
);

CREATE TABLE document_tag_rel (
    document_id BIGINT      NOT NULL,   -- 文件 ID
    tag_id      BIGINT      NOT NULL,   -- 标签 ID
    dept_id     BIGINT      NOT NULL,
    created_by  BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (document_id, tag_id),
    CONSTRAINT fk_dtr_doc FOREIGN KEY (document_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE CASCADE,
    CONSTRAINT fk_dtr_tag FOREIGN KEY (tag_id, dept_id)
        REFERENCES sys_tag (id, dept_id) ON DELETE CASCADE,
    CONSTRAINT fk_dtr_creator FOREIGN KEY (created_by, dept_id)
        REFERENCES sys_user (id, dept_id) ON DELETE SET NULL (created_by)
);

CREATE TABLE document_version (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    BIGINT      NOT NULL,
    dept_id        BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE RESTRICT,
    version_no     INT         NOT NULL,                       -- 版本号，同一文件内从 1 递增
    storage_bucket VARCHAR(64) NOT NULL DEFAULT 'docai',       -- 版本对象所在桶，可与主文件不同
    storage_key    VARCHAR(512) NOT NULL,
    file_size      BIGINT      NOT NULL,
    sha256         CHAR(64)    NOT NULL,
    change_note    VARCHAR(255),                               -- 变更说明
    created_by     BIGINT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_ver_no CHECK (version_no > 0),
    CONSTRAINT fk_ver_doc FOREIGN KEY (document_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE CASCADE,
    CONSTRAINT fk_ver_creator FOREIGN KEY (created_by, dept_id)
        REFERENCES sys_user (id, dept_id) ON DELETE SET NULL (created_by)
);

