CREATE TABLE document_block (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id         BIGINT      NOT NULL,                      -- 冗余租户列；向量检索必须先按它过滤，否则跨租户召回
    document_id     BIGINT      NOT NULL,
    block_index     INT         NOT NULL,                      -- 块在文档内的序号，从 0 开始
    block_type      VARCHAR(16) NOT NULL,                      -- 块类型：TITLE 标题 / PARAGRAPH 段落 / TABLE 表格 / IMAGE 图片
    content         TEXT        NOT NULL,                      -- 块的文本内容
    table_json      JSONB,                                     -- 表格结构化内容（TABLE 块必填）
    heading_path    VARCHAR(512),                              -- 所属标题路径，如 "第一章/1.1"
    cell_ref        VARCHAR(128),                              -- 来源单元格范围，如 A1:D5
    page_no         INT,                                       -- 页码
    char_len        INT         NOT NULL DEFAULT 0,            -- 字符数
    token_count     INT,                                       -- 估算 token 数，供上下文预算使用
    embedding       vector(1536),                              -- 文本向量（1536 维，余弦距离）
    embedding_model VARCHAR(64),                               -- 生成该向量的模型标识
    embedding_dim   SMALLINT,                                  -- 向量维度
    embedded_at     TIMESTAMPTZ,                               -- 向量化时间
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_block_type       CHECK (block_type IN ('TITLE', 'PARAGRAPH', 'TABLE', 'IMAGE')),
    CONSTRAINT ck_block_idx        CHECK (block_index >= 0),
    CONSTRAINT ck_block_table_json CHECK (block_type <> 'TABLE' OR table_json IS NOT NULL),
    CONSTRAINT uq_block_id_dept    UNIQUE (id, dept_id),
    CONSTRAINT fk_block_doc FOREIGN KEY (document_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE CASCADE
);

-- =====================================================================
-- 5. 抽取 Schema 与模板映射
-- =====================================================================

CREATE TABLE extract_schema (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id     BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE RESTRICT,
    creator_id  BIGINT,                            -- 创建人
    name        VARCHAR(128) NOT NULL,             -- Schema 名称
    prompt_text TEXT,                              -- 创建时的自然语言原始描述
    schema_json JSONB       NOT NULL,              -- 字段定义 JSON：{"fields":[{"key","label","type","unit","required","description"}]}
    version     INT         NOT NULL DEFAULT 1,    -- 版本号，同名可多版本共存
    status      VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',  -- 状态：DRAFT 草稿 / ACTIVE 启用 / ARCHIVED 归档
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ,
    CONSTRAINT ck_schema_status  CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_schema_json    CHECK (jsonb_typeof(schema_json) = 'object'),
    CONSTRAINT uq_schema_id_dept UNIQUE (id, dept_id),
    CONSTRAINT fk_schema_creator FOREIGN KEY (creator_id, dept_id)
        REFERENCES sys_user (id, dept_id) ON DELETE RESTRICT
);

CREATE TABLE template_field_mapping (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id         BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE RESTRICT,
    template_doc_id BIGINT      NOT NULL,                      -- 模板文件 ID
    schema_id       BIGINT,                                    -- 关联的抽取 Schema
    field_key       VARCHAR(64) NOT NULL,                      -- 字段标识，对应 schema_json 中的 key
    anchor_type     VARCHAR(16) NOT NULL,                      -- 锚点类型：BOOKMARK 书签 / CELL 单元格 / PLACEHOLDER 占位符
    anchor_ref      VARCHAR(128) NOT NULL,                     -- 锚点值：书签名 / 单元格地址 / 占位符文本
    sheet_name      VARCHAR(64),                               -- Excel 工作表名
    value_type      VARCHAR(16) NOT NULL DEFAULT 'TEXT',       -- 值类型：TEXT/NUMBER/DATE/BOOLEAN/ENUM
    value_format    VARCHAR(64),                               -- 显示格式，如 yyyy-MM-dd / #,##0.00
    unit            VARCHAR(16),                               -- 单位，如 万元
    is_required     BOOLEAN     NOT NULL DEFAULT FALSE,        -- 是否必填
    ordinal         INT         NOT NULL DEFAULT 0,            -- 回填顺序
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_tfm_anchor  CHECK (anchor_type IN ('BOOKMARK', 'CELL', 'PLACEHOLDER')),
    CONSTRAINT ck_tfm_type    CHECK (value_type IN ('TEXT', 'NUMBER', 'DATE', 'BOOLEAN', 'ENUM')),
    CONSTRAINT fk_tfm_doc FOREIGN KEY (template_doc_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE CASCADE,
    CONSTRAINT fk_tfm_schema FOREIGN KEY (schema_id, dept_id)
        REFERENCES extract_schema (id, dept_id) ON DELETE RESTRICT
);

-- =====================================================================
-- 6. 任务流转
-- =====================================================================

CREATE TABLE task (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id          BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE RESTRICT,
    creator_id       BIGINT,
    assignee_id      BIGINT,                                   -- 处理人
    task_type        VARCHAR(16) NOT NULL,                     -- 任务类型：EXTRACT 信息抽取 / FILL 模板填表
    schema_id        BIGINT,
    template_doc_id  BIGINT,                                   -- 填表使用的模板文件
    schema_snapshot  JSONB,                                    -- 建单时的 Schema 快照，保证结果可复现
    status           VARCHAR(16) NOT NULL DEFAULT 'PENDING',   -- 状态：PENDING/ASSIGNED/PROCESSING/COMPLETED/FAILED/CANCELLED
    progress         SMALLINT    NOT NULL DEFAULT 0,           -- 进度百分比 0-100
    priority         SMALLINT    NOT NULL DEFAULT 5,           -- 优先级，1 最高、9 最低
    payload_json     JSONB,                                    -- 任务入参快照（字段范围等）
    result_json      JSONB,                                    -- 执行结果摘要
    result_doc_id    BIGINT,                                   -- 产出的文件 ID
    error_msg        TEXT,                                     -- 失败原因
    attempt_count    SMALLINT    NOT NULL DEFAULT 0,           -- 已尝试次数
    claimed_at       TIMESTAMPTZ,                              -- 认领时间
    lease_expires_at TIMESTAMPTZ,                              -- 租约到期时间，超时可被他人重新认领
    started_at       TIMESTAMPTZ,                              -- 开始执行时间
    completed_at     TIMESTAMPTZ,                              -- 结束时间（完成/失败/取消）
    version_no       INT         NOT NULL DEFAULT 0,           -- 乐观锁版本号，更新时 WHERE version_no = ?
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at       TIMESTAMPTZ,
    CONSTRAINT ck_task_type          CHECK (task_type IN ('EXTRACT', 'FILL')),
    CONSTRAINT ck_task_status        CHECK (status IN ('PENDING', 'ASSIGNED', 'PROCESSING', 'COMPLETED', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_task_progress      CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_task_priority      CHECK (priority BETWEEN 1 AND 9),
    CONSTRAINT ck_task_time          CHECK (completed_at IS NULL OR completed_at >= created_at),
    CONSTRAINT ck_task_terminal_time CHECK (status NOT IN ('COMPLETED', 'FAILED', 'CANCELLED') OR completed_at IS NOT NULL),
    CONSTRAINT ck_task_failed_msg    CHECK (status <> 'FAILED' OR error_msg IS NOT NULL),
    CONSTRAINT ck_task_done_progress CHECK (status <> 'COMPLETED' OR progress = 100),
    CONSTRAINT uq_task_id_dept       UNIQUE (id, dept_id),
    CONSTRAINT fk_task_creator FOREIGN KEY (creator_id, dept_id)
        REFERENCES sys_user (id, dept_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_assignee FOREIGN KEY (assignee_id, dept_id)
        REFERENCES sys_user (id, dept_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_schema FOREIGN KEY (schema_id, dept_id)
        REFERENCES extract_schema (id, dept_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_tpl FOREIGN KEY (template_doc_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_result FOREIGN KEY (result_doc_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE RESTRICT
);

CREATE TABLE task_document_rel (
    task_id     BIGINT      NOT NULL,
    document_id BIGINT      NOT NULL,
    dept_id     BIGINT      NOT NULL,
    ord         INT         NOT NULL DEFAULT 0,     -- 文件在任务内的排序
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (task_id, document_id),
    CONSTRAINT fk_tdr_task FOREIGN KEY (task_id, dept_id)
        REFERENCES task (id, dept_id) ON DELETE CASCADE,
    CONSTRAINT fk_tdr_doc FOREIGN KEY (document_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE CASCADE
);

-- =====================================================================
-- 7. 结果与审计
