CREATE TABLE sys_dept (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 主键
    parent_id   BIGINT      REFERENCES sys_dept(id) ON DELETE RESTRICT,    -- 上级部门；NULL 表示根部门
    dept_code   VARCHAR(32),                                              -- 部门编码，用于外部系统对接
    name        VARCHAR(64) NOT NULL,                                     -- 部门名称，同层不可重名
    sort_no     INT         NOT NULL DEFAULT 0,                           -- 同级排序号，升序
    status      VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',                    -- 状态：ACTIVE 启用 / DISABLED 停用
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),                       -- 创建时间
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),                       -- 最后更新时间
    deleted_at  TIMESTAMPTZ,                                              -- 软删时间；NULL 表示未删除
    CONSTRAINT ck_dept_status   CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_dept_not_self CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE sys_user (
    id                  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id             BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE RESTRICT,  -- 所属部门（租户隔离键）
    username            VARCHAR(64) NOT NULL,                        -- 登录名，未删除账号间全局唯一
    password_hash       VARCHAR(255) NOT NULL,                       -- BCrypt 摘要，禁止明文或可逆加密
    real_name           VARCHAR(64),                                 -- 姓名
    email               VARCHAR(128),                                -- 邮箱，同部门内唯一
    phone               VARCHAR(32),                                 -- 手机号
    role                VARCHAR(32) NOT NULL,                        -- 角色：ADMIN 管理员 / DISPATCHER 分配员 / PROCESSOR 处理员
    status              VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',       -- 状态：ACTIVE / DISABLED / LOCKED
    last_login_at       TIMESTAMPTZ,                                 -- 最近一次登录时间
    password_updated_at TIMESTAMPTZ,                                 -- 密码最近修改时间
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ,
    CONSTRAINT ck_user_role    CHECK (role IN ('ADMIN', 'DISPATCHER', 'PROCESSOR')),
    CONSTRAINT ck_user_status  CHECK (status IN ('ACTIVE', 'DISABLED', 'LOCKED')),
    CONSTRAINT uq_user_id_dept UNIQUE (id, dept_id)
);

CREATE TABLE dept_email_config (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id        BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE CASCADE,
    email_address  VARCHAR(128) NOT NULL,                     -- 收件邮箱地址
    imap_host      VARCHAR(128) NOT NULL,                     -- IMAP 服务器地址
    imap_port      SMALLINT    NOT NULL DEFAULT 993,          -- IMAP 端口，SSL 通常 993
    use_ssl        BOOLEAN     NOT NULL DEFAULT TRUE,         -- 是否启用 SSL
    folder         VARCHAR(64) NOT NULL DEFAULT 'INBOX',      -- 监听的邮件文件夹
    auth_code_enc  TEXT        NOT NULL,                      -- IMAP 授权码密文，禁止明文
    auth_code_kid  VARCHAR(64),                               -- 加密密钥版本号，支持轮换
    last_uid       BIGINT      NOT NULL DEFAULT 0,            -- 已处理的最大 UID，增量拉取位点
    uid_validity   BIGINT      NOT NULL DEFAULT 0,            -- UID 空间标识；变化说明 UID 已重置，需清空 last_uid 重扫
    last_check_at  TIMESTAMPTZ,                               -- 最近一次拉取时间
    last_error     TEXT,                                      -- 最近一次拉取失败原因
    enabled        BOOLEAN     NOT NULL DEFAULT TRUE,         -- 是否启用该邮箱
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ,
    CONSTRAINT ck_email_port       CHECK (imap_port BETWEEN 1 AND 65535),
    CONSTRAINT uq_emailcfg_id_dept UNIQUE (id, dept_id)
);

CREATE TABLE email_whitelist (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id     BIGINT      NOT NULL REFERENCES sys_dept(id) ON DELETE CASCADE,
    match_type  VARCHAR(16) NOT NULL DEFAULT 'DOMAIN',    -- 匹配方式：DOMAIN 域名 / ADDRESS 完整地址 / SUFFIX 后缀
    pattern     VARCHAR(255) NOT NULL,                    -- 匹配内容，如 supplier.com
    remark      VARCHAR(255),                             -- 备注
    enabled     BOOLEAN     NOT NULL DEFAULT TRUE,        -- 是否启用
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_wl_type CHECK (match_type IN ('DOMAIN', 'ADDRESS', 'SUFFIX'))
);

