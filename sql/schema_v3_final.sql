CREATE TABLE extract_result (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id           BIGINT      NOT NULL,
    task_id           BIGINT      NOT NULL,
    document_id       BIGINT      NOT NULL,
    field_key         VARCHAR(64) NOT NULL,
    value_type        VARCHAR(16) NOT NULL DEFAULT 'TEXT',   -- 值类型，决定使用哪个 value_* 列
    field_value       TEXT,                                  -- 展示用字段值（含单位）
    value_num         NUMERIC(20,4),                         -- 归一化数值，供聚合与排序
    value_date        DATE,                                  -- 归一化日期
    value_bool        BOOLEAN,                               -- 归一化布尔
    value_unit        VARCHAR(16),                           -- 值单位
    raw_value         TEXT,                                  -- 模型原始输出
    confidence        NUMERIC(5,4),                          -- 置信度 0-1
    evidence_block_id BIGINT,                                -- 证据所在块 ID
    evidence_text     TEXT,                                  -- 证据原文快照，块被清理后仍可追溯
    is_selected       BOOLEAN     NOT NULL DEFAULT FALSE,    -- 是否为该字段终稿，每字段至多一条
    is_modified       BOOLEAN     NOT NULL DEFAULT FALSE,    -- 是否被人工修改
    is_verified       BOOLEAN     NOT NULL DEFAULT FALSE,    -- 是否人工确认
    modified_by       BIGINT,                                -- 修改人
    modified_at       TIMESTAMPTZ,                           -- 修改时间
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_res_conf CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
    CONSTRAINT ck_res_type CHECK (value_type IN ('TEXT', 'NUMBER', 'DATE', 'BOOLEAN', 'ENUM')),
    CONSTRAINT ck_res_num  CHECK (value_type <> 'NUMBER' OR field_value IS NULL OR value_num IS NOT NULL),
    CONSTRAINT fk_res_task FOREIGN KEY (task_id, dept_id)
        REFERENCES task (id, dept_id) ON DELETE CASCADE,
    CONSTRAINT fk_res_doc FOREIGN KEY (document_id, dept_id)
        REFERENCES document (id, dept_id) ON DELETE RESTRICT,
    CONSTRAINT fk_res_block FOREIGN KEY (evidence_block_id, dept_id)
        REFERENCES document_block (id, dept_id) ON DELETE SET NULL (evidence_block_id),
    CONSTRAINT fk_res_modifier FOREIGN KEY (modified_by, dept_id)
        REFERENCES sys_user (id, dept_id) ON DELETE SET NULL (modified_by)
);

CREATE TABLE extract_result_history (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id      BIGINT      NOT NULL REFERENCES extract_result(id) ON DELETE CASCADE,  -- 对应的抽取结果
    task_id        BIGINT      NOT NULL,
    field_key      VARCHAR(64) NOT NULL,
    old_value      TEXT,                                   -- 修改前的值
    new_value      TEXT,                                   -- 修改后的值
    old_confidence NUMERIC(5,4),                           -- 修改前的置信度
    operator_id    BIGINT,                                 -- 操作人
    reason         VARCHAR(255),                           -- 修改原因
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE task_log (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id     BIGINT      NOT NULL,
    task_id     BIGINT      NOT NULL,
    operator_id BIGINT,                                    -- 操作人
    action      VARCHAR(64) NOT NULL,                      -- 动作：CREATE/ASSIGN/CLAIM/EXTRACT/COMPLETE/FAIL/REASSIGN
    from_status VARCHAR(16),                               -- 变更前状态
    to_status   VARCHAR(16),                               -- 变更后状态
    detail      JSONB,                                     -- 附加信息
    ip_addr     INET,                                      -- 操作来源 IP
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sys_audit_log (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id     BIGINT,
    user_id     BIGINT,                                    -- 操作用户；登录失败等场景为空
    action      VARCHAR(64) NOT NULL,                      -- 动作：LOGIN/LOGIN_FAIL/USER_CREATE/DOC_DELETE/CFG_UPDATE 等
    target_type VARCHAR(32),                               -- 操作对象类型
    target_id   BIGINT,                                    -- 操作对象 ID
    detail      JSONB,                                     -- 附加信息
    ip_addr     INET,
    user_agent  VARCHAR(255),                              -- 客户端 UA
    success     BOOLEAN     NOT NULL DEFAULT TRUE,         -- 是否成功
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

